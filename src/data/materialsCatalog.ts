export const mapCatalogItemToBudgetItem = (
  item: CatalogMaterialItem,
  quantity = 1
): BudgetItem => {
  return {
    id: item.id + '-' + Date.now().toString().slice(-4),
    name: item.nombre,
    price: item.precioEstimado,
    category: item.categoria,
    unit: item.unidadMedida,
    skuCode: item.skuCode,
    quantity: quantity,
  };
};


/**
 * Compares the total connected load on a circuit against the breaker's nominal capacity and curve (B, C, D).
 * If load/overcurrent exceeds curve thresholds per IEC 60898-1 / RIC N°02, trips the breaker to OFF and logs event.
 */
export function calculateShortCircuit(
  breaker: InteractiveComponent,
  totalConnectedWatts: number,
  supplyVoltage: number = 220
): {
  isTripped: boolean;
  tripType?: 'MAGNETIC_SHORT_CIRCUIT' | 'THERMAL_OVERLOAD';
  tripReason?: string;
  tripCurrentAmps: number;
  timeMs: number;
  iccAmps: number;
  normReference: string;
} {
  const nominalIn = breaker.ampacity || 16;
  const loadAmps = totalConnectedWatts / supplyVoltage;
  const curve = breaker.curve || 'C';

  // Curve magnetic multiplier thresholds
  let magMin = 5;
  let magMax = 10;
  if (curve === 'B') {
    magMin = 3;
    magMax = 5;
  } else if (curve === 'D') {
    magMin = 10;
    magMax = 20;
  } else if (curve === 'K') {
    magMin = 8;
    magMax = 14;
  } else if (curve === 'Z') {
    magMin = 2;
    magMax = 3;
  }

  // Instantaneous magnetic short circuit trip
  if (loadAmps >= nominalIn * magMin) {
    return {
      isTripped: true,
      tripType: 'MAGNETIC_SHORT_CIRCUIT',
      tripReason: `Disparo Instantáneo por Cortocircuito (Curva ${curve}): Corriente ${loadAmps.toFixed(1)}A supera el umbral magnético de ${magMin}x In (${nominalIn * magMin}A).`,
      tripCurrentAmps: loadAmps,
      iccAmps: Math.round(loadAmps * 12),
      timeMs: Math.round(11 + Math.random() * 6), // 11-17ms
      normReference: `RIC N°02 Art. 5 (Disparo Magnético Curva ${curve} IEC 60898-1)`,
    };
  }

  // Thermal overload (> 1.13x - 1.45x In)
  if (loadAmps > nominalIn * 1.13) {
    return {
      isTripped: true,
      tripType: 'THERMAL_OVERLOAD',
      tripReason: `Disparo por Sobrecarga Térmica: Carga conectada (${totalConnectedWatts}W → ${loadAmps.toFixed(1)}A) sobrepasa la capacidad nominal ${nominalIn}A (Curva ${curve}).`,
      tripCurrentAmps: loadAmps,
      iccAmps: Math.round(loadAmps),
      timeMs: Math.round(110 + Math.random() * 80),
      normReference: `RIC N°02 Art. 5.3 (Protección Térmica de Conductores)`,
    };
  }

  return {
    isTripped: false,
    tripCurrentAmps: loadAmps,
    timeMs: 0,
    iccAmps: 0,
    normReference: 'RIC N°02',
  };
}

/**
 * Saves a fault snapshot to localStorage and dispatches a notification event for WorkReportTab.
 */
export function saveFaultSnapshot(
  fault: ActiveElectricalFault,
  compList: InteractiveComponent[],
  wireList: Wire[],
  st: string
): FaultSnapshot {
  const snapshot: FaultSnapshot = {
    id: `snap_${Date.now()}_${Math.random().toString(36).slice(2, 6)}`,
    timestamp: new Date().toLocaleTimeString('es-CL'),
    title: fault.title,
    faultType: fault.type,
    trippedCompId: fault.trippedCompId,
    trippedCompName: fault.trippedCompName,
    iccAmps: fault.iccAmps,
    timeMs: fault.timeMs,
    normReference: fault.normReference,
    description: fault.description,
    componentsState: compList.map(c => ({
      id: c.id,
      name: c.name,
      type: c.type,
      x: c.x,
      y: c.y,
      w: c.w,
      h: c.h,
      ampacity: c.ampacity,
      curve: c.curve,
      isTripped: c.isTripped,
      isOff: c.isOff,
    })),
    wiresState: wireList.map(w => ({
      id: w.id,
      fromCompId: w.fromCompId,
      fromTermId: w.fromTermId,
      toCompId: w.toCompId,
      toTermId: w.toTermId,
      color: w.color,
    })),
    supplyType: st,
    faultLocation: { x: fault.x, y: fault.y },
  };

  try {
    const existingStr = localStorage.getItem('neovolt_fault_snapshots');
    const list: FaultSnapshot[] = existingStr ? JSON.parse(existingStr) : [];
    const updated = [snapshot, ...list].slice(0, 25);
    localStorage.setItem('neovolt_fault_snapshots', JSON.stringify(updated));
    window.dispatchEvent(new CustomEvent('neovolt_fault_snapshot_created', { detail: snapshot }));
  } catch (err) {
    console.warn('Error saving snapshot:', err);
  }

  return snapshot;
}


  const [isCapturing, setIsCapturing] = useState(false);
  const [captureFeedback, setCaptureFeedback] = useState<string | null>(null);
  const [shutterFlash, setShutterFlash] = useState(false);

  // Dynamic live voltage fluctuation
  const [liveVolts, setLiveVolts] = useState(222.4);
  useEffect(() => {
    if (!isEnergized) {
      setLiveVolts(0);
      return;
    }
    const interval = setInterval(() => {
      const base = isThreePhase ? 380.5 : 222.4;
      const jitter = (Math.sin(Date.now() / 1000) * 1.5 + (Math.random() * 0.6 - 0.3));
      setLiveVolts(+(base + jitter).toFixed(1));
    }, 800);
    return () => clearInterval(interval);
  }, [isEnergized, isThreePhase]);

  // Three.js Scene, Renderer & Animation References
  const sceneRef = useRef<THREE.Scene | null>(null);
  const rendererRef = useRef<THREE.WebGLRenderer | null>(null);
  const cameraRef = useRef<THREE.PerspectiveCamera | null>(null);
  const doorMeshRef = useRef<THREE.Group | null>(null);
  const clickableMeshesRef = useRef<Array<{ mesh: THREE.Object3D; comp: InteractiveComponent; leverMesh?: THREE.Mesh }>>([]);
  const pilotLightSourcesRef = useRef<THREE.PointLight[]>([]);
  const particleSystemRef = useRef<THREE.Points | null>(null);

  // Camera Orbit & Pan State
  const isOrbitingRef = useRef(false);
  const isPanningRef = useRef(false);
  const previousMousePosRef = useRef({ x: 0, y: 0 });
  const cameraTargetRef = useRef<THREE.Vector3>(new THREE.Vector3(0, 0, 0));
  const cameraSphericalRef = useRef({ radius: 48, theta: Math.PI / 4, phi: Math.PI / 3 });


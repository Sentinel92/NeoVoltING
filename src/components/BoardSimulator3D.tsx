/**
 * Creates ultra-high-resolution procedural canvas textures for real electrical component faceplates (PBR)
 */
function createComponentFaceplateTexture(
  type: 'MCB' | 'IGA' | 'RCD' | 'DPS' | 'PILOT_LIGHTS' | 'LOAD' | 'GRID' | string,
  tag: string,
  name: string,
  ampacity?: number,
  curve?: string,
  isThreePhase?: boolean,
  isOverflow?: boolean,
  isEnergized?: boolean,
  isOff?: boolean,
  liveVolts: number = 222.4
): THREE.CanvasTexture {
  const canvas = document.createElement('canvas');
  canvas.width = 1024;
  canvas.height = 2048;
  const ctx = canvas.getContext('2d');
  if (!ctx) return new THREE.CanvasTexture(canvas);

  // Background body tone with subtle industrial texture
  let bgGradient = ctx.createLinearGradient(0, 0, 1024, 2048);
  if (type === 'DPS') {
    bgGradient.addColorStop(0, '#0c2340');
    bgGradient.addColorStop(0.3, '#081a30');
    bgGradient.addColorStop(0.7, '#051324');
    bgGradient.addColorStop(1, '#020b17');
  } else if (type === 'PILOT_LIGHTS') {
    bgGradient.addColorStop(0, '#1e2638');
    bgGradient.addColorStop(0.5, '#131926');
    bgGradient.addColorStop(1, '#0c101a');
  } else {
    // High-grade RAL 7035 light grey electrical engineering thermoplastic
    bgGradient.addColorStop(0, '#fafcff');
    bgGradient.addColorStop(0.2, '#f1f5f9');
    bgGradient.addColorStop(0.6, '#e2e8f0');
    bgGradient.addColorStop(0.9, '#cbd5e1');
    bgGradient.addColorStop(1, '#94a3b8');
  }

  ctx.fillStyle = bgGradient;
  ctx.fillRect(0, 0, 1024, 2048);

  // Molded plastic chamfers and hairline seam lines
  ctx.strokeStyle = type === 'DPS' ? '#1e3a8a' : '#94a3b8';
  ctx.lineWidth = 8;
  ctx.strokeRect(16, 16, 992, 2016);

  // Terminal cage recesses on top and bottom
  ctx.fillStyle = type === 'DPS' ? '#030a14' : '#475569';
  ctx.fillRect(32, 32, 960, 240);
  ctx.fillRect(32, 1776, 960, 240);

  // Ventilation / arc-chute side relief vents
  ctx.fillStyle = type === 'DPS' ? '#020810' : '#64748b';
  for (let y = 320; y < 500; y += 40) {
    ctx.fillRect(60, y, 120, 18);
    ctx.fillRect(844, y, 120, 18);
  }

  // Laser Etched Brand Header & SEC Approval
  ctx.fillStyle = type === 'DPS' ? '#38bdf8' : '#0f172a';
  ctx.font = 'bold 72px sans-serif';
  ctx.textAlign = 'center';
  ctx.fillText('NEOVOLT SEC', 512, 380);

  ctx.font = 'bold 40px monospace';
  ctx.fillStyle = type === 'DPS' ? '#94a3b8' : '#64748b';
  ctx.fillText('IEC/EN 60898-1 • 50Hz', 512, 440);

  // Circuit Tag Badge Plate (e.g., [ C1 ], [ RCD-1 ], [ DPS-1 ], [ IGA-1 ])
  const displayTag = tag || (type === 'MCB' ? name.split(' ')[0] : type);
  ctx.fillStyle = isOverflow ? '#dc2626' : (type === 'DPS' ? '#0284c7' : '#0284c7');
  ctx.beginPath();
  ctx.roundRect(192, 500, 640, 140, 32);
  ctx.fill();

  ctx.fillStyle = '#ffffff';
  ctx.font = '900 80px monospace';
  ctx.fillText(displayTag, 512, 600);

  // Ratings, breaking capacities and technical markings
  if (type === 'MCB' || type === 'IGA') {
    const mainCurve = curve || 'C';
    const mainAmps = ampacity || (type === 'IGA' ? 25 : 16);

    ctx.fillStyle = '#0f172a';
    ctx.font = '900 156px sans-serif';
    ctx.fillText(`${mainCurve}${mainAmps}`, 512, 860);

    // Voltage rating
    ctx.font = 'bold 48px monospace';
    ctx.fillStyle = '#475569';
    ctx.fillText(isThreePhase ? '400V~ / 230V~' : '230V~', 512, 960);

    // Breaking capacity box: 6000 [3] (IEC standard)
    ctx.strokeStyle = '#0f172a';
    ctx.lineWidth = 8;
    ctx.strokeRect(352, 1040, 320, 112);
    ctx.fillStyle = '#0f172a';
    ctx.font = 'bold 64px monospace';
    ctx.fillText('6000', 460, 1120);
    ctx.strokeRect(600, 1048, 60, 96);
    ctx.font = 'bold 52px monospace';
    ctx.fillText('3', 630, 1120);

    // Schematic symbol etched
    ctx.strokeStyle = '#475569';
    ctx.lineWidth = 8;
    ctx.beginPath();
    ctx.moveTo(420, 1280);
    ctx.lineTo(420, 1340);
    ctx.lineTo(520, 1300);
    ctx.lineTo(520, 1400);
    ctx.stroke();

    // SEC Certification holographic / QR seal placeholder
    ctx.fillStyle = '#cbd5e1';
    ctx.fillRect(436, 1480, 152, 152);
    ctx.strokeStyle = '#0f172a';
    ctx.lineWidth = 4;
    ctx.strokeRect(436, 1480, 152, 152);
    ctx.fillStyle = '#0f172a';
    ctx.font = '900 28px monospace';
    ctx.fillText('SEC-CL', 512, 1570);
  } else if (type === 'RCD') {
    const mainAmps = ampacity || 25;
    ctx.fillStyle = '#0f172a';
    ctx.font = '900 136px sans-serif';
    ctx.fillText(`In ${mainAmps}A`, 512, 820);

    ctx.fillStyle = '#dc2626';
    ctx.font = '900 96px sans-serif';
    ctx.fillText('IΔn 30mA', 512, 960);

    ctx.font = 'bold 48px monospace';
    ctx.fillStyle = '#475569';
    ctx.fillText('Tipo AC • [ T ] Test', 512, 1060);

    // RCD Test button icon
    ctx.fillStyle = '#f59e0b';
    ctx.beginPath();
    ctx.arc(512, 1240, 72, 0, Math.PI * 2);
    ctx.fill();
    ctx.fillStyle = '#000000';
    ctx.font = '900 88px sans-serif';
    ctx.fillText('T', 512, 1270);

    ctx.font = 'bold 36px sans-serif';
    ctx.fillStyle = '#64748b';
    ctx.fillText('Pulsar Mensualmente', 512, 1360);
  } else if (type === 'DPS') {
    ctx.fillStyle = '#38bdf8';
    ctx.font = '900 104px sans-serif';
    ctx.fillText('SURGE PROTECT', 512, 820);

    ctx.fillStyle = '#facc15';
    ctx.font = 'bold 68px monospace';
    ctx.fillText('SPD T2 • 20/40kA', 512, 940);

    ctx.fillStyle = '#ffffff';
    ctx.font = '48px monospace';
    ctx.fillText('Uc: 275V~ | Up ≤ 1.5kV', 512, 1060);

    // Live Digital LED Voltmeter Display Screen
    ctx.fillStyle = isEnergized ? '#02182b' : '#030a14';
    ctx.fillRect(256, 1140, 512, 150);
    ctx.strokeStyle = isEnergized ? '#0284c7' : '#1e293b';
    ctx.lineWidth = 8;
    ctx.strokeRect(256, 1140, 512, 150);

    if (isEnergized) {
      ctx.fillStyle = '#38bdf8';
      ctx.shadowColor = '#0284c7';
      ctx.shadowBlur = 20;
      ctx.font = '900 96px monospace';
      ctx.fillText(`${liveVolts.toFixed(1)} V~`, 512, 1250);
      ctx.shadowBlur = 0;
    } else {
      ctx.fillStyle = '#334155';
      ctx.font = '900 80px monospace';
      ctx.fillText('---.- V', 512, 1245);
    }

    // Optical cartridge status window
    ctx.fillStyle = '#052e16';
    ctx.strokeStyle = '#22c55e';
    ctx.lineWidth = 8;
    ctx.strokeRect(312, 1360, 400, 100);
    ctx.fillRect(312, 1360, 400, 100);
    ctx.fillStyle = '#4ade80';
    ctx.font = '900 56px monospace';
    ctx.fillText('STATUS: OK', 512, 1430);
  } else if (type === 'PILOT_LIGHTS') {
    ctx.fillStyle = '#f59e0b';
    ctx.font = 'bold 72px sans-serif';
    ctx.fillText('SEÑALIZACIÓN SEC', 512, 840);
    ctx.fillStyle = '#94a3b8';
    ctx.font = '48px monospace';
    ctx.fillText('LED 230V~ 50Hz', 512, 940);

    ctx.fillStyle = isEnergized ? '#22c55e' : '#64748b';
    ctx.font = '900 52px monospace';
    ctx.fillText(isEnergized ? '⚡ RED ENERGIZADA' : '⭕ RED DESCONECTADA', 512, 1100);
  }

  // Capacity overflow visual warning label
  if (isOverflow) {
    ctx.fillStyle = '#7f1d1d';
    ctx.fillRect(40, 1580, 944, 160);
    ctx.strokeStyle = '#ef4444';
    ctx.lineWidth = 12;
    ctx.strokeRect(40, 1580, 944, 160);
    ctx.fillStyle = '#ffffff';
    ctx.font = '900 64px sans-serif';
    ctx.fillText('⚠️ SOBRECUPO DIN', 512, 1680);
  }

  const texture = new THREE.CanvasTexture(canvas);
  texture.needsUpdate = true;
  return texture;
}


  const [viewPreset, setViewPreset] = useState<'iso' | 'front' | 'top' | 'side' | 'bornes_top' | 'bornes_bot'>('iso');

  // Sync energized state between props and internal
  const isEnergized = externalIsEnergized !== undefined ? externalIsEnergized : internalEnergized;

  // Screenshot capture states

    // Studio Ambient Light for neutral fill
    const ambientLight = new THREE.AmbientLight(0xffffff, 0.45);
    scene.add(ambientLight);

    // Studio Key Light (High-angle soft shadow caster)
    const keyLight = new THREE.DirectionalLight(0xffffff, 1.6);
    keyLight.position.set(25, 45, 30);
    keyLight.castShadow = true;
    keyLight.shadow.mapSize.width = 2048;
    keyLight.shadow.mapSize.height = 2048;
    keyLight.shadow.bias = -0.0001;
    keyLight.shadow.camera.near = 10;
    keyLight.shadow.camera.far = 120;
    keyLight.shadow.camera.left = -30;
    keyLight.shadow.camera.right = 30;
    keyLight.shadow.camera.top = 30;
    keyLight.shadow.camera.bottom = -30;
    scene.add(keyLight);

    // Studio Fill Light (Cool daylight tone to soften contrast)
    const fillLight = new THREE.DirectionalLight(0x94a3b8, 0.7);
    fillLight.position.set(-25, 20, 25);
    scene.add(fillLight);

    // Left Specular Rim Light (sharp plastic bevel highlights)
    const leftRimLight = new THREE.DirectionalLight(0x38bdf8, 0.9);

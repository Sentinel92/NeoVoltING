    cabinetGroup.add(peBar);

    const nBar = createTerminalBar(false, -cabHeight / 2 + 4.2);
    cabinetGroup.add(nBar);

    // Front Smoked Acrylic Viewing Door with Hinges
    const doorGroup = new THREE.Group();
    doorGroup.position.set(-cabWidth / 2, 0, cabDepth / 2);
    doorMeshRef.current = doorGroup;

    const acrylicMat = new THREE.MeshPhysicalMaterial({
      color: 0x0369a1,
      transparent: true,
      opacity: 0.35,
      roughness: 0.08,
      metalness: 0.05,
      transmission: 0.8,
      ior: 1.52,
    });

    const doorMesh = new THREE.Mesh(new THREE.BoxGeometry(cabWidth, cabHeight, 0.4), acrylicMat);
    doorMesh.position.set(cabWidth / 2, 0, 0);
    doorGroup.add(doorMesh);

